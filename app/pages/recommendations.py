"""D. Anti-Pattern & Index Recommendations page."""
from __future__ import annotations

import streamlit as st

from app.components.sidebar import render_page_header
from src.services.workbench_service import FullAnalysisBundle, analyze_query_end_to_end
from src.db.connection_manager import ConnectionManager
from src.db.metadata_store import MetadataStore


def render_recommendations_page() -> None:
    render_page_header(
        "Optimization & Index Recommendations",
        "SQL anti-pattern diagnostics and advisory PostgreSQL index suggestions backed by AST, catalog, and EXPLAIN evidence.",
    )

    conn_mgr: ConnectionManager = st.session_state["qt_conn_mgr"]
    store: MetadataStore = st.session_state["qt_store"]
    bundle: FullAnalysisBundle | None = st.session_state.get("qt_last_analysis")

    if bundle is None:
        st.info("No query analyzed yet. Analyzing current SQL from Query Editor...")
        sql_text = st.session_state.get("qt_editor_sql", "")
        if sql_text.strip():
            bundle = analyze_query_end_to_end(
                sql_text,
                conn_manager=conn_mgr,
                metadata_store=store,
                analyze_explain=conn_mgr.is_connected,
                buffers=conn_mgr.is_connected,
                timeout_ms=st.session_state["qt_timeout_ms"],
                persist=False,
            )
            st.session_state["qt_last_analysis"] = bundle
        else:
            return

    with st.expander("Analyzed SQL Statement", expanded=False):
        st.code(bundle.formatted_sql or bundle.sql_text, language="sql")

    tab_ap, tab_idx = st.tabs(
        [
            f"SQL Anti-Patterns ({len(bundle.antipatterns)})",
            f"Index Recommendations ({len(bundle.index_recommendations)})",
        ]
    )

    with tab_ap:
        if not bundle.antipatterns:
            st.success("No common SQL anti-patterns were detected in this statement.")
        else:
            sev_filter = st.multiselect(
                "Filter by Severity",
                options=["High", "Medium", "Low"],
                default=["High", "Medium", "Low"],
            )
            shown = [f for f in bundle.antipatterns if f.severity in sev_filter]
            for f in shown:
                with st.expander(
                    f"[{f.severity}] {f.issue_name} — Confidence: {f.confidence} ({f.evidence_basis})",
                    expanded=True,
                ):
                    st.markdown("**Affected SQL Fragment:**")
                    st.code(f.affected_fragment, language="sql")
                    st.markdown(f"**Explanation:** {f.explanation}")
                    st.markdown(f"**Why It May Affect Performance:** {f.performance_impact}")
                    st.markdown(f"**When This Pattern Is Acceptable:** {f.when_acceptable}")
                    st.markdown(f"**Suggested Improvement:** {f.suggested_improvement}")

    with tab_idx:
        st.markdown(
            "<div class='qt-advisory'>"
            "<strong>Safety Guarantee:</strong> All index statements below are strictly advisory recommendations, "
            "not guaranteed improvements. QueryTrellis never creates indexes or modifies schemas automatically. "
            "Always benchmark writes/storage trade-offs before applying DDL in production."
            "</div>",
            unsafe_allow_html=True,
        )

        if not bundle.index_recommendations:
            st.info(
                "No additional index recommendations generated. Either existing indexes already cover "
                "detected filters/joins, referenced tables are small, or predicates are non-sargable."
            )
        else:
            all_ddl = "\n".join(r.suggested_sql for r in bundle.index_recommendations)
            st.download_button(
                "Download All Recommended DDL (.sql)",
                data=(
                    "-- Advisory Index Recommendations generated by QueryTrellis\n"
                    "-- Review carefully before running manually.\n\n" + all_ddl + "\n"
                ).encode("utf-8"),
                file_name="querytrellis_index_recommendations.sql",
                mime="text/sql",
            )
            for r in bundle.index_recommendations:
                with st.expander(
                    f"[{r.confidence} Confidence] {r.index_type} on {r.table_name}({', '.join(r.columns)})",
                    expanded=True,
                ):
                    st.markdown(f"**Related Condition / Evidence:** `{r.related_condition}`")
                    st.markdown(f"**Evidence Sources:** {', '.join(r.evidence_sources)}")
                    st.markdown("**Advisory SQL Statement (Copyable):**")
                    st.code(r.suggested_sql, language="sql")
                    st.markdown(f"**Why It May Help:** {r.why_it_helps}")
                    st.markdown(f"**Existing Index Check:** {r.existing_index_status}")
                    st.markdown(f"**Write & Storage Overhead:** {r.write_and_storage_overhead}")
                    st.markdown(f"**When It May Not Help:** {r.when_not_helpful}")
